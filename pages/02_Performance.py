from __future__ import annotations



from pathlib import Path



import pandas as pd

import plotly.express as px

import streamlit as st



from utils.data_loaders import (

    load_performance_metrics,

    performance_metrics_mtime,

)

from utils.optional_imports import OPTIONAL_MODULES

from utils.model_loader import compute_cached_cv_metrics, get_artifact_mtimes

from utils.visualizations import create_confusion_matrix_heatmap, create_performance_metrics_chart



st.header("Model Performance")

st.info("The dataset is highly imbalanced (~96.4% no claim / 3.6% claim). ROC-AUC is the primary metric.")



metrics = load_performance_metrics(performance_metrics_mtime())

results_path = Path("training_results.json")

optimal_threshold = metrics.get("optimal_threshold", 0.5)



if results_path.exists():

    updated = metrics.get("source_mtime", "unknown")

    st.success(

        "✅ **Hold-out test** metrics from `training_results.json` "

        f"(optimal threshold **{optimal_threshold:.3f}**, tuned on train)."

    )

    st.caption(f"Last file update: **{updated}**. After retraining, use *Clear cache* if values do not change.")

else:

    st.warning("⚠️ Using fallback metrics. Run `python run_training.py`.")



col1, col2, col3, col4, col5 = st.columns(5)

col1.metric("ROC-AUC", f"{metrics.get('roc_auc', 0):.3f}")

col2.metric("F1-Score", f"{metrics.get('f1_score', 0):.3f}")

col3.metric("Precision", f"{metrics.get('precision', 0):.3f}")

col4.metric("Recall", f"{metrics.get('recall', 0):.3f}")

col5.metric("Optimal threshold", f"{optimal_threshold:.3f}")



default_f1 = metrics.get("f1_score_default_threshold")

if default_f1 is not None:

    st.caption(

        f"Hold-out test with default threshold **0.5**: "

        f"**F1 = {default_f1:.3f}** (see `test_f1_default` in training_results.json). "

        f"With optimal threshold **{optimal_threshold:.3f}**: F1 = {metrics.get('f1_score', 0):.3f}."

    )



with st.expander("Probability calibration (Issue 2 — threshold vs well-calibrated probabilities)"):

    cal_path = Path("models/artifacts/calibration_curve.png")

    st.markdown(

        """

        **Rationale:** ROC-AUC measures ranking; with ~3.6% positives the 0.5 threshold collapses F1,

        but probabilities may still be well calibrated with a train-tuned threshold around ~0.06.

        """

    )

    if cal_path.exists():

        st.image(str(cal_path), caption="Calibration curve (hold-out test, generated by the pipeline)")

        brier = metrics.get("brier_score")

        if brier is not None:

            st.caption(f"Brier score (test): **{brier:.4f}** — lower is better.")

    else:

        st.info("Run `python run_training_full.py` to generate `models/artifacts/calibration_curve.png`.")

    st.markdown(

        "**Roadmap:** monthly recalibration in production (Platt/isotonic) and Brier monitoring in Shadow Monitor."

    )



if OPTIONAL_MODULES.validation_available:

    with st.expander("Cross-validation (reference — does not replace hold-out test)"):

        cv_f1_hint = f"{default_f1:.3f}" if default_f1 is not None else "N/A"

        st.caption(

            f"CV uses **10k samples**, **3 folds**, and sklearn computes F1 with **threshold 0.5** "

            f"(comparable to hold-out F1 @ 0.5 = **{cv_f1_hint}**, not F1 with optimal threshold)."

        )

        try:

            artifact_state = get_artifact_mtimes()

            if artifact_state is not None:

                with st.spinner("Running cross-validation..."):

                    cv_metrics = compute_cached_cv_metrics(

                        model_mtime=artifact_state["model_mtime"],

                        feature_engineer_mtime=artifact_state["feature_engineer_mtime"],

                        train_mtime=artifact_state["train_mtime"],

                        sample_size=10000,

                        n_splits=3,

                    )

                cv_col1, cv_col2 = st.columns(2)

                cv_col1.metric(

                    "CV ROC-AUC (mean)",

                    f"{cv_metrics['metrics']['roc_auc']['test_mean']:.3f}",

                )

                cv_f1_mean = cv_metrics["metrics"]["f1"]["test_mean"]

                cv_col2.metric(

                    "CV F1 @ 0.5 (mean)",

                    f"{cv_f1_mean:.3f}",

                )

                if default_f1 is not None:

                    st.caption(

                        f"Hold-out reference: F1 @ 0.5 = **{default_f1:.3f}** | "

                        f"CV F1 @ 0.5 = **{cv_f1_mean:.3f}** (10k sample, 3 folds)."

                    )

        except Exception as exc:

            st.warning(f"Cross-validation unavailable: {exc}")



st.markdown("---")

st.subheader("Performance Metrics Visualization")

accuracy_val = metrics.get("accuracy")

if accuracy_val is not None:

    st.caption(

        f"**Accuracy ({accuracy_val:.1%})** is shown for completeness but is misleading on this dataset: "

        f"~96% of policies have no claim, so a naive 'always no claim' model scores ~96% accuracy. "

        f"Prefer **ROC-AUC** and **F1 @ optimal threshold ({optimal_threshold:.3f})** for evaluation."

    )

st.plotly_chart(create_performance_metrics_chart(metrics), use_container_width=True)



st.markdown("---")

st.subheader("Confusion Matrix")

cm = metrics.get("confusion_matrix")

if cm:

    st.plotly_chart(create_confusion_matrix_heatmap(cm), use_container_width=True)

    st.caption(

        f"Source: `{metrics.get('confusion_matrix_source', 'threshold_optimization_results.json')}` "

        f"— TN={cm['tn']:,}, FP={cm['fp']:,}, FN={cm['fn']:,}, TP={cm['tp']:,} "

        f"@ threshold **{optimal_threshold:.3f}**."

    )

else:

    st.warning(

        "Confusion matrix unavailable. Run "

        "`python src/models/find_optimal_threshold.py` to generate "

        "`threshold_optimization_results.json`."

    )



st.markdown("---")

roc_auc_val = metrics.get("roc_auc", 0.5)

comparison_data = pd.DataFrame(

    {

        "Model": ["Random Baseline", "Naive (Always No Claim)", "Our EBM Model", "Top Kaggle Models"],

        "ROC-AUC": [0.500, 0.500, roc_auc_val, 0.648],

    }

)

fig_comparison = px.bar(

    comparison_data,

    x="Model",

    y="ROC-AUC",

    color="ROC-AUC",

    color_continuous_scale="Viridis",

    title="ROC-AUC Comparison with Baselines",

)

st.plotly_chart(fig_comparison, use_container_width=True)
st.caption(
    "0.648 is an approximate public-leaderboard order of magnitude for this Kaggle "
    "competition (not reproduced in this repo; not a verified benchmark run)."
)

