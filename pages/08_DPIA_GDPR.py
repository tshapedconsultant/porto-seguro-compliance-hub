"""
DPIA / EIPD (GDPR Art. 35) — evidence for an AEPD innovation lab.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import streamlit as st

from src.governance.dpia_workspace.reports import assessment_pdf_bytes
from src.governance.dpia_workspace.store import AssessmentStore
from utils.control_plane_notice import CONTROL_PLANE_BANNER

DPIA_PATHS = (Path("gdpr_dpia_v1.json"), Path("docs/dpia_gdpr_v1.json"))


def _load_dpia() -> tuple[dict, Path]:
    for path in DPIA_PATHS:
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8")), path
    return {}, Path("gdpr_dpia_v1.json")


dpia, dpia_path = _load_dpia()

st.title("EIPD / DPIA — GDPR Art. 35")
st.caption("Data Protection Impact Assessment · AEPD innovation lab")
st.warning(CONTROL_PLANE_BANNER)

disclaimer = dpia.get("disclaimer", {})
st.warning(
    disclaimer.get("text_en")
    or disclaimer.get(
        "text_es",
        "Reference architecture. This is not a notification to the supervisory authority.",
    )
)

if not dpia:
    st.error("Could not find `gdpr_dpia_v1.json`.")
    st.stop()

residual = dpia.get("residual_risk_summary", {})
why = dpia.get("why_dpia_is_required", {})
art22 = dpia.get("data_subject_rights", {}).get("automated_decisions_art_22", {})

c1, c2, c3, c4 = st.columns(4)
c1.metric("Screening scope", "Design / demo")
c2.metric("Residual risk", residual.get("overall", "N/A"))
st.caption(residual.get("residual_status", "estimated_pending_verification"))
c3.metric("Art. 22 human intervention", residual.get("human_intervention", "required"))
c4.metric("AEPD notification", "No (demo)")

gdpr_block = dpia.get("gdpr") or {}
if gdpr_block:
    st.markdown("#### Structured GDPR evidence block")
    st.caption(
        "Generated by `src/governance/gdpr_evidence.py`. Technical evidence only — "
        "not a legal determination. See `docs/governance/GDPR_EVIDENCE.md`."
    )
    g1, g2, g3, g4 = st.columns(4)
    g1.metric("Assurance", gdpr_block.get("assurance_level", "evidence_only"))
    g2.metric("Status", gdpr_block.get("compliance_status", "not_a_legal_determination"))
    g3.metric("Review required", "Yes" if gdpr_block.get("review_required", True) else "No")
    g4.metric("Open gaps", str(len(gdpr_block.get("open_gaps", []))))
    evals = gdpr_block.get("evaluations", {})
    if evals:
        rows = []
        for name, section in evals.items():
            rows.append(
                {
                    "Evaluation": name,
                    "Applicability": section.get("applicability"),
                    "Evidence": section.get("evidence_status"),
                    "Control": section.get("control_status"),
                    "Review": section.get("review_required"),
                }
            )
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)
    with st.expander("Open GDPR gaps", expanded=False):
        for item in gdpr_block.get("open_gaps", []):
            st.write(f"- **{item.get('section')}:** {item.get('gap')}")
    with st.expander("Pending legal / DPO decisions", expanded=False):
        for item in gdpr_block.get("pending_legal_or_dpo_decisions", []):
            st.write(f"- {item}")

st.markdown("---")
st.header("For a 3-minute walkthrough")
st.markdown(
    """
1. **What is processed:** claim-probability scoring as underwriting support (not automatic premium).
2. **Why there is a DPIA:** GDPR Art. 35(3)(a) — systematic large-scale evaluation with effects analogous to an insurance decision.
3. **Demo nuance:** the Kaggle file uses publisher-anonymised `ps_*` columns. That is **not** a Recital 26 legal finding. GDPR applicability stays **unknown** until a controller assesses identifiability; the pack is a **design control** for a live processing.
4. **Logic (Art. 15(1)(h))** vs **safeguards (Art. 22(3)):** the EBM explains the logic; Art. 22(3) is human intervention, the right to express a view, and the right to contest.
5. **Download** the JSON: it is the record-keeping system, the same role as the AI Act conformity declaration.
"""
)

st.header("Description of the processing")
proc = dpia.get("processing_description", {})
col_a, col_b = st.columns(2)
with col_a:
    st.subheader("Purpose")
    for item in proc.get("purposes", []):
        st.write(f"- {item}")
    st.subheader("Out of scope")
    for item in proc.get("out_of_scope", []):
        st.write(f"- {item}")
with col_b:
    cats = proc.get("data_categories", {})
    st.subheader("Data (demo)")
    st.write(f"**Source:** {cats.get('demo_dataset', 'N/A')}")
    st.write(f"**Records:** {cats.get('records', 'N/A')}")
    st.write(f"**Direct identifiers:** {cats.get('direct_identifiers', 'N/A')}")
    st.write(f"**Art. 9 (special categories):** {cats.get('special_categories_art_9', 'N/A')}")
    st.write(f"**International transfers:** {proc.get('international_transfers', 'N/A')}")

with st.expander("Legal basis (demo vs production)", expanded=False):
    basis = proc.get("legal_basis", {})
    st.markdown(f"**Demo:** {basis.get('demo', {}).get('position', '')}")
    st.markdown("**Production analogue (not asserted here):**")
    for item in basis.get("production_analogue", {}).get("candidate_bases", []):
        st.write(f"- {item}")

st.header("Why Art. 35")
st.write(why.get("article_35_3_a", ""))
st.info(why.get("demo_nuance", ""))
st.caption(why.get("aepd_list", ""))

st.header("Principles (Art. 5)")
principles = dpia.get("necessity_and_proportionality", {})
principle_labels = {
    "purpose_limitation_art_5_1_b": "Purpose limitation",
    "data_minimisation_art_5_1_c": "Data minimisation",
    "accuracy_art_5_1_d": "Accuracy",
    "storage_limitation_art_5_1_e": "Storage limitation",
    "integrity_confidentiality_art_5_1_f": "Integrity and confidentiality",
    "accountability_art_5_2": "Accountability",
}
for key, label in principle_labels.items():
    if key in principles:
        st.markdown(f"**{label}.** {principles[key]}")

st.header("Rights (Arts. 12–22)")
rights = dpia.get("data_subject_rights", {})
st.markdown(f"**Information (13–14).** {rights.get('information_art_13_14', '')}")
st.markdown(f"**Access / logic (15(1)(h)).** {rights.get('access_art_15_1_h', rights.get('access_art_15', ''))}")
st.markdown(f"**Automated decisions (22).** {art22.get('position', '')}")
st.markdown("**Safeguards in this repository:**")
for item in art22.get("implementation_in_this_repo", []):
    st.write(f"- {item}")

st.header("Risk register")
st.caption("Score = likelihood × severity (1–5). Residual after controls in the code.")
rows = []
for risk in dpia.get("risk_register", []):
    rows.append(
        {
            "ID": risk.get("id"),
            "Risk": risk.get("risk"),
            "Inherent": risk.get("inherent_score"),
            "Residual": risk.get("residual_score"),
            "Status": risk.get("status"),
        }
    )
if rows:
    st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)

with st.expander("Risk and mitigation detail", expanded=False):
    for risk in dpia.get("risk_register", []):
        st.markdown(f"**{risk.get('id')} — residual {risk.get('residual_score')}**")
        st.write(risk.get("risk"))
        for m in risk.get("mitigations", []):
            st.write(f"- {m}")

st.header("Measures already in the code")
for item in dpia.get("mitigations_in_code", []):
    st.markdown(f"- **{item.get('control')}** — `{item.get('evidence')}`")

st.header("GDPR × EU AI Act crosswalk")
st.caption("Two regimes, one evidence trail. The lab can jump to the EU AI Act page.")
cross = dpia.get("gdpr_eu_ai_act_crosswalk", [])
if cross:
    st.table(pd.DataFrame(cross))

st.page_link("pages/06_EU_AI_Act.py", label="Open EU AI Act article-by-article mapping")
st.page_link("pages/03_Explainability.py", label="Open native explainability (Art. 15(1)(h) / AI Act Art. 13)")

st.header("Dynamic file")
st.caption("AssessmentStore (not the static pack). A material change invalidates an internal approval.")
store = AssessmentStore()
dyn = None
if "EIPD-porto-demo" in store.list_ids():
    dyn = store.get("EIPD-porto-demo")
else:
    st.info("No dynamic file on disk. Seeding writes a local JSON.")
    if st.button("Create demo file on disk"):
        dyn = store.ensure_demo()
if dyn is not None:
    st.write(
        {
            "id": dyn.assessment_id,
            "decision_state": dyn.decision_state,
            "screening_outcome": dyn.screening.get("outcome"),
            "screening_scope": dyn.screening.get("scope"),
            "risks": len(dyn.risks),
        }
    )
    st.download_button(
        label="Download dynamic-file PDF",
        data=assessment_pdf_bytes(dyn),
        file_name=f"{dyn.assessment_id}.pdf",
        mime="application/pdf",
    )

st.markdown("---")
st.subheader("Evidence pack")
payload = json.dumps(dpia, indent=2, ensure_ascii=False)
st.download_button(
    label="Download EIPD (JSON)",
    data=payload,
    file_name="gdpr_dpia_v1.json",
    mime="application/json",
)
st.caption(f"Record-keeping system on disk: `{dpia_path}` · DPO signature pending (demo).")
st.caption(residual.get("article_36", ""))
